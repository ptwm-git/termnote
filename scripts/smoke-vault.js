(async()=>{
  const p=app.plugins.plugins['agent-note-terminal'],m=p.manager;
  const wait=ms=>new Promise(r=>setTimeout(r,ms));
  const ensure=(ok,message)=>{if(!ok)throw Error(message);};
  const folder='终端插件验收-'+Date.now();await app.vault.createFolder(folder);
  const [one,two,three]=await Promise.all([m.newNote(folder),m.newNote(folder),m.newNote(folder)]);
  ensure(new Set([one.record.path,two.record.path,three.record.path]).size===3,'并发创建重名');
  ensure(one.record.path.endsWith('终端页面一.md')&&three.record.path.endsWith('终端页面三.md'),'默认名称不正确');
  await Promise.all([m.launch(one),m.launch(two),m.launch(three)]);
  await wait(700);
  ensure([one,two,three].every(s=>s.record.state==='running'),'Shell 启动失败 '+[one.error,two.error,three.error].join(' / '));
  const view=await p.getView();view.select(one);
  one.write("printf 'SESSION_ONE_中文\\n'; claude --version\r");
  two.write("printf 'SESSION_TWO_独立输出\\n'; codex --version\r");
  three.write("printf 'SESSION_THREE_第三页\\n'\r");
  await wait(1600);
  let first=await app.vault.read(app.vault.getAbstractFileByPath(one.record.path));
  let second=await app.vault.read(app.vault.getAbstractFileByPath(two.record.path));
  ensure(first.includes('SESSION_ONE_中文')&&!first.includes('SESSION_TWO_独立输出'),'会话一串写或未保存');
  ensure(second.includes('SESSION_TWO_独立输出')&&!second.includes('SESSION_ONE_中文'),'会话二串写或未保存');
  await m.rename(two,'重命名后的会话');two.write("printf 'AFTER_RENAME_OK\\n'\r");
  m.hide(one);one.write("printf 'BACKGROUND_STILL_SAVED\\n'\r");view.select(three);
  await wait(900);
  ensure((await app.vault.read(app.vault.getAbstractFileByPath(two.record.path))).includes('AFTER_RENAME_OK'),'改名后记录失败');
  ensure((await app.vault.read(app.vault.getAbstractFileByPath(one.record.path))).includes('BACKGROUND_STILL_SAVED'),'收起后未保存');
  const oldId=three.record.id,oldPath=three.record.path;
  await app.vault.delete(app.vault.getAbstractFileByPath(oldPath));await wait(700);
  const recreated=await app.vault.create(oldPath,'# 用户新建的同路径笔记\n');
  const fresh=await m.attach(recreated);ensure(fresh.record.id!==oldId,'复用了已删除会话');
  const copied=await app.vault.create(folder+'/复制的终端记录.md',await app.vault.read(app.vault.getAbstractFileByPath(one.record.path)));
  const copySession=await m.attach(copied);ensure(copySession.record.id!==one.record.id,'复制文件未独立绑定');
  one.write('cat '+JSON.stringify(one.record.path.split('/').pop())+'\r');await wait(900);
  ensure(!one.saveError,'输出自身笔记阻断保存 '+one.saveError);
  view.leaf.detach();await wait(100);one.write("printf 'AFTER_VIEW_CLOSED\\n'\r");await wait(800);
  ensure((await app.vault.read(app.vault.getAbstractFileByPath(one.record.path))).includes('AFTER_VIEW_CLOSED'),'关闭视图后未持续保存');
  const reopened=await p.getView();m.show(one);reopened.select(one);
  await Promise.all([...m.sessions.values()].map(s=>s.stop()));await m.persist();await wait(300);
  ensure([one,two].every(s=>!s.child&&!s.saveError),'停止收尾或笔记保存失败');
  return {ok:true,folder,records:[one,two,three,fresh,copySession].map(s=>({id:s.record.id,path:s.record.path,state:s.record.state,saveError:s.saveError})),agentVersions:{claude:first.includes('Claude Code'),codex:second.includes('codex-cli')},visibleTabs:document.querySelectorAll('.ant-tab').length};
})()
